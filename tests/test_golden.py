"""Golden comparison tests: verify Python implementation produces consistent results.

These tests load reference data generated by generate_references.py and re-run
the same algorithms, checking that results match within numerical tolerance.
This catches regressions and ensures the Python port stays consistent.

For true Rust-vs-Python comparison, the Rust workspace should generate equivalent
golden data and the paths should be swapped here.
"""

import json
import math
from pathlib import Path

import numpy as np
import pytest

GOLDEN_DIR = Path(__file__).parent / "golden"


def assert_quats_close(actual, expected, tol=1e-6):
    """Compare two TimeQuat maps, handling quaternion double-cover."""
    assert set(actual.keys()) == set(expected.keys()), \
        f"Timestamp mismatch: extra={set(actual.keys()) - set(expected.keys())}, missing={set(expected.keys()) - set(actual.keys())}"
    for ts in actual:
        q1 = actual[ts].quaternion()
        q2 = expected[ts].quaternion()
        if np.dot(q1, q2) < 0:
            q2 = -q2
        np.testing.assert_allclose(q1, q2, atol=tol, err_msg=f"Quaternion mismatch at t={ts}")


def load_golden(name: str) -> dict:
    path = GOLDEN_DIR / f"{name}.json"
    if not path.exists():
        pytest.skip(f"Golden data file not found: {path}")
    with open(path) as f:
        return json.load(f)


