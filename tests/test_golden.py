# Distortion model golden tests
# ---------------------------------------------------------------------------

class TestGoldenDistortion:
    """Re-run distortion/undistortion on golden test points and compare."""

    @pytest.mark.parametrize("model_name", [
        "opencv_fisheye", "opencv_standard", "poly3", "poly5", "ptlens",
    ])
    def test_distortion_matches_golden(self, model_name):
        from pygyroflow.stabilization.distortion_models import from_name
        from pygyroflow.types.kernel_params import kernel_params_from_dict

        golden = load_golden(f"distortion_{model_name}")
        model = from_name(model_name)

        coeffs = golden["coefficients"]
        kp = kernel_params_from_dict({
            "k1": coeffs["k1"],
            "k2": coeffs["k2"],
            "k3": coeffs["k3"],
        })

        for tp in golden["test_points"]:
            x, y, z = tp["input_3d"]
            dx, dy = model.distort_point(x, y, z, kp)

            np.testing.assert_allclose([dx, dy], tp["distorted"], atol=1e-8,
                                       err_msg=f"distort_point mismatch for {model_name} at ({x},{y},{z})")

            ux, uy = model.undistort_point(dx, dy, kp)
            np.testing.assert_allclose([ux, uy], tp["undistorted"], atol=1e-8,
                                       err_msg=f"undistort_point mismatch for {model_name} at ({dx},{dy})")

            roundtrip_err = math.sqrt((x - ux) ** 2 + (y - uy) ** 2)
            np.testing.assert_allclose(roundtrip_err, tp["roundtrip_error"], atol=1e-8)


