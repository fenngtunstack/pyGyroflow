class TestGoldenSmoothing:
    """Re-run smoothing algorithms on golden input and compare."""

    def _load_quats(self, quats_dict):
        from pygyroflow.types.quaternion import Quat64
        result = {}
        for ts_str, q_list in quats_dict.items():
            result[int(ts_str)] = Quat64.from_quaternion(q_list)
        return result

    @pytest.mark.parametrize("algo_name,params", [
        ("default_0.3", {"smoothness": 0.3}),
        ("default_0.7", {"smoothness": 0.7}),
        ("plain", {"time_constant": 0.3}),
    ])
    def test_smoothing_matches_golden(self, algo_name, params):
        from pygyroflow.smoothing import DefaultAlgo, PlainSmoothing
        from pygyroflow.stabilization import ComputeParams

        golden = load_golden(f"smoothing_{algo_name}")
        input_quats = self._load_quats(golden["input_quaternions"])

        algo_cls = DefaultAlgo if algo_name.startswith("default") else PlainSmoothing
        algo = algo_cls()
        for k, v in params.items():
            algo.set_parameter(k, v)

        n = len(input_quats)
        duration_ms = golden["duration_ms"]
        cp = ComputeParams(
            width=1920, height=1080, output_width=1920, output_height=1080,
            frame_count=n, scaled_fps=n / (duration_ms / 1000.0),
            scaled_duration_ms=duration_ms,
            quaternions=input_quats, fovs=[1.0] * n, fov_scale=1.0,
        )

        result = algo.smooth(input_quats, duration_ms, cp)
        expected = self._load_quats(golden["output_quaternions"])
        assert_quats_close(result, expected, tol=1e-10)


