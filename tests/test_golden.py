class TestGoldenFrameTransform:
    """Re-run frame transform computation on golden inputs and compare."""

    def test_frame_transform_matches_golden(self):
        from pygyroflow.types.quaternion import Quat64
        from pygyroflow.stabilization import ComputeParams, FrameTransform

        golden = load_golden("frame_transform")

        quats = {}
        smoothed = {}
        for t_info in golden["transforms"]:
            t_us = int(t_info["timestamp_ms"] * 1000)
            quats[t_us] = Quat64.from_euler_angles(0.0, 0.0, t_info["frame"] * 0.005)
            smoothed[t_us] = Quat64.from_euler_angles(0.0, 0.0, t_info["frame"] * 0.005 * 0.5)

        cp = ComputeParams(
            width=1920, height=1080, output_width=1920, output_height=1080,
            frame_count=60, scaled_fps=60.0, scaled_duration_ms=1000.0,
            quaternions=quats, smoothed_quaternions=smoothed,
            fovs=[1.0] * 60, fov_scale=1.0,
            camera_matrix=np.array([
                [1000.0, 0.0, 960.0],
                [0.0, 1000.0, 540.0],
                [0.0, 0.0, 1.0],
            ]),
            distortion_coeffs=[0.0] * 12,
            frame_readout_time=0.0,
        )

        for t_info in golden["transforms"]:
            frame_idx = t_info["frame"]
            timestamp_ms = t_info["timestamp_ms"]
            ft = FrameTransform.at_timestamp(cp, timestamp_ms, frame_idx)

            assert ft.matrices.shape[0] == t_info["matrix_count"], \
                f"Matrix count mismatch at frame {frame_idx}"
            if t_info["matrices_0"]:
                np.testing.assert_allclose(
                    ft.matrices[0].tolist(), t_info["matrices_0"],
                    atol=1e-5, err_msg=f"Matrix mismatch at frame {frame_idx}",
                )
            np.testing.assert_allclose(
                ft.fov, t_info["fov"], atol=1e-6,
                err_msg=f"FOV mismatch at frame {frame_idx}",
            )


# ---------------------------------------------------------------------------
# VQF golden test (uses same synthetic IMU data)
# ---------------------------------------------------------------------------

class TestGoldenVQF:
    """VQF integration golden test — verifies deterministic output."""

    def test_vqf_deterministic(self):
        from pygyroflow.imu_integration.vqf import VQFIntegrator
        from pygyroflow.types.time_types import TimeIMU

        imu_data = load_golden("imu_data")
        imu_list = [
            TimeIMU(
                timestamp_ms=s["timestamp_ms"],
                gyro=np.array(s["gyro"]) if s["gyro"] else None,
                accl=np.array(s["accl"]) if s["accl"] else None,
                magn=np.array(s["magn"]) if s["magn"] else None,
            )
            for s in imu_data["samples"]
        ]

        integrator = VQFIntegrator()
        result = integrator.integrate(imu_list, imu_data["duration_ms"])

        # Run again — must produce identical results
        result2 = integrator.integrate(imu_list, imu_data["duration_ms"])
        assert_quats_close(result, result2, tol=1e-15)

        # Verify output covers the expected time range
        assert len(result) > 0
        ts_sorted = sorted(result.keys())
        assert ts_sorted[0] == 0
        assert ts_sorted[-1] >= int(imu_data["duration_ms"] * 1000) - 10000
